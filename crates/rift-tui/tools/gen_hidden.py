#!/usr/bin/env python3
"""Writes src/hidden_table.rs: code points drawn as escapes, not as text.

Usage: gen_hidden.py DerivedGeneralCategory.txt DerivedCoreProperties.txt

Both files come from https://www.unicode.org/Public/UCD/latest/ucd/
(extracted/DerivedGeneralCategory.txt and DerivedCoreProperties.txt).
The table is general category Cf plus Default_Ignorable_Code_Point; Cc is
checked with `char::is_control`. Standard library only.
"""
import re
import sys


def ranges(path, wanted):
    version = open(path).readline().strip("# \n")
    out = []
    for line in open(path):
        m = re.match(r"([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*(\w+)", line)
        if m and m.group(3) == wanted:
            lo = int(m.group(1), 16)
            out.append((lo, int(m.group(2) or m.group(1), 16)))
    return version, out


def merge(items):
    merged = []
    for lo, hi in sorted(items):
        if merged and lo <= merged[-1][1] + 1:
            merged[-1] = (merged[-1][0], max(hi, merged[-1][1]))
        else:
            merged.append((lo, hi))
    return merged


v1, cf = ranges(sys.argv[1], "Cf")
v2, di = ranges(sys.argv[2], "Default_Ignorable_Code_Point")
rows = merge(cf + di)
with open("src/hidden_table.rs", "w") as f:
    f.write("// Generated by tools/gen_hidden.py from %s and %s.\n" % (v1, v2))
    f.write("// Cf plus Default_Ignorable_Code_Point, inclusive ranges, sorted.\n")
    f.write("pub(crate) const HIDDEN: &[(u32, u32)] = &[\n")
    for lo, hi in rows:
        f.write("    (0x%04X, 0x%04X),\n" % (lo, hi))
    f.write("];\n")
